CREATE TABLE IF NOT EXISTS "users" (
                                       "id" UUID NOT NULL,
                                       "first_names" TEXT NOT NULL,
                                       "last_names" TEXT NOT NULL,
                                       "email" TEXT NOT NULL UNIQUE,
                                       "password_hash" TEXT NOT NULL,
                                       "created_at" TIMESTAMPTZ NOT NULL,
                                       "updated_at" TIMESTAMPTZ,
                                       "deleted_at" TIMESTAMPTZ,
                                       PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "roles" (
                                       "id" BIGSERIAL NOT NULL,
                                       "name" TEXT NOT NULL UNIQUE,
                                       PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "permissions" (
                                             "id" BIGSERIAL NOT NULL,
                                             "name" TEXT NOT NULL UNIQUE,
                                             PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "users_roles" (
                                             "user_id" UUID NOT NULL,
                                             "role_id" BIGINT NOT NULL,
                                             PRIMARY KEY("user_id", "role_id")
    );

CREATE TABLE IF NOT EXISTS "roles_permissions" (
                                                   "role_id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                                   "permission_id" BIGINT NOT NULL,
                                                   PRIMARY KEY("role_id", "permission_id")
    );

CREATE TABLE IF NOT EXISTS "refresh_tokens" (
                                                "id" UUID NOT NULL,
                                                "user_id" UUID NOT NULL,
                                                "token_hash" TEXT NOT NULL,
                                                "expires_at" TIMESTAMP NOT NULL,
                                                "revoked_at" TIMESTAMPTZ,
                                                "created_at" TIMESTAMPTZ NOT NULL,
                                                "updated_at" TIMESTAMPTZ,
                                                PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "experiments" (
                                             "id" UUID NOT NULL,
                                             "name" VARCHAR(255) NOT NULL,
    "source" VARCHAR(255) NOT NULL,
    "created_at" TIMESTAMPTZ NOT NULL,
    "updated_at" TIMESTAMPTZ,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "variants" (
                                          "id" UUID NOT NULL,
                                          "experiment_id" UUID NOT NULL,
                                          "container_image_id" UUID,
                                          "type" VARCHAR(255) NOT NULL,
    "key" VARCHAR(255) NOT NULL,
    "callable" VARCHAR(255) NOT NULL,
    "name" VARCHAR(255) NOT NULL,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "runs" (
                                      "id" UUID NOT NULL,
                                      "experiment_id" UUID NOT NULL,
                                      "input_file_id" UUID NOT NULL,
                                      "input_format" VARCHAR(255) NOT NULL,
    "status" VARCHAR(255) NOT NULL,
    "started_at" TIMESTAMPTZ,
    "ended_at" TIMESTAMPTZ,
    "created_at" TIMESTAMPTZ NOT NULL,
    "updated_at" TIMESTAMPTZ,
    "deleted_at" TIMESTAMPTZ,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "measurements" (
                                              "id" UUID NOT NULL,
                                              "run_id" UUID NOT NULL,
                                              "variant_id" UUID NOT NULL,
                                              "output_file_id" UUID,
                                              "output_format" VARCHAR(255) NOT NULL,
    "status" VARCHAR(255) NOT NULL,
    "error" TEXT,
    "started_at" TIMESTAMPTZ NOT NULL,
    "ended_at" TIMESTAMPTZ,
    "created_at" TIMESTAMPTZ NOT NULL,
    "updated_at" TIMESTAMPTZ,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "comparisons" (
                                             "id" UUID NOT NULL,
                                             "run_id" UUID NOT NULL,
                                             "control_measurement_id" UUID NOT NULL,
                                             "candidate_measurement_id" UUID NOT NULL,
                                             "output_file_id" UUID,
                                             "output_format" VARCHAR(255) NOT NULL,
    "created_at" TIMESTAMPTZ NOT NULL,
    "updated_at" TIMESTAMPTZ,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "artifacts" (
                                           "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "bucket" TEXT NOT NULL,
    "object_key" TEXT NOT NULL,
    "filename" TEXT NOT NULL,
    "content_type" TEXT NOT NULL,
    "created_at" TIMESTAMPTZ NOT NULL,
    PRIMARY KEY("id")
    );

CREATE TABLE IF NOT EXISTS "container_images" (
                                                  "id" UUID NOT NULL,
                                                  "registry" VARCHAR(255) NOT NULL,
    "repository" VARCHAR(255) NOT NULL,
    "digest" VARCHAR(255) NOT NULL,
    "tag" VARCHAR(255),
    "created_at" TIMESTAMPTZ NOT NULL,
    "updated_at" TIMESTAMPTZ,
    PRIMARY KEY("id")
    );

